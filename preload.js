const { contextBridge, ipcRenderer, webFrame } = require('electron');

window.addEventListener('DOMContentLoaded', () => document.documentElement.classList.add('os-' + process.platform, 'desktop-app', ...(process.argv.includes('--resenha-round-window') ? ['win-round'] : [])));

contextBridge.exposeInMainWorld('resenhaNative', {
  platform: process.platform,
  performanceSample: () => ipcRenderer.invoke('performance:sample'),
  savePerformance: (report) => ipcRenderer.invoke('performance:save',report),
  setWindowColors: (background, foreground) => ipcRenderer.send('window:colors', background, foreground),
  setWindowMaterial: (on) => ipcRenderer.invoke('window:material', !!on),
  spotify: { status: () => ipcRenderer.invoke('spotify:status'), login: () => ipcRenderer.invoke('spotify:login'), token: () => ipcRenderer.invoke('spotify:token'), logout: () => ipcRenderer.invoke('spotify:logout') },
  onWindowVisible: (fn) => ipcRenderer.on('window:visible', (e, visible) => fn(visible)),
  windowControl: (action) => ipcRenderer.send('window:control', action),
  setAppIcon: (key, pngs) => ipcRenderer.invoke('app:icon', { key, pngs }),
  onWindowMaximized: (fn) => ipcRenderer.on('window:maximized', (e, maximized) => fn(maximized)),
  rooms: {locations:()=>ipcRenderer.invoke('rooms:locations'),list:()=>ipcRenderer.invoke('rooms:list'),save:s=>ipcRenderer.invoke('rooms:save',s),import:codes=>ipcRenderer.invoke('rooms:import',codes),inspect:code=>ipcRenderer.invoke('rooms:inspect',code),claim:o=>ipcRenderer.invoke('rooms:claim',o)},
  hostBackground: value=>ipcRenderer.invoke('window:host-background',value),
  startHost: (opts) => ipcRenderer.invoke('host:start', opts),
  stopHost: (code) => ipcRenderer.invoke('host:stop', code),
  cacheFile: (f) => ipcRenderer.invoke('cache:file', f),
  setZoom: (z) => webFrame.setZoomFactor(Math.max(0.7, Math.min(1.5, Number(z) || 1))),
  mobileAccess: () => ipcRenderer.invoke('host:mobile'),
  pwaInvite: (code) => ipcRenderer.invoke('pwa:invite', code),
  hostNetwork: () => ipcRenderer.invoke('host:network'),
  captureInfo: (captureToken) => ipcRenderer.invoke('capture:info', captureToken),
  captureStatus: (info) => ipcRenderer.invoke('capture:status', info),
  captureDiagnostics: () => ipcRenderer.invoke('capture:diagnostics'),
  captureSystem: () => ipcRenderer.invoke('capture:system'),
  setCaptureCompatibility: (enabled) => ipcRenderer.invoke('capture:compatibility', enabled),
  onCaptureFailure: (fn) => ipcRenderer.on('capture:failure', (e, message) => fn(message)),
  screenSources: () => ipcRenderer.invoke('screen:sources'),
  selectScreen: (sel) => ipcRenderer.invoke('screen:select', sel),
  setShortcuts: (map) => ipcRenderer.invoke('shortcuts:set', map),
  notify: (n) => ipcRenderer.invoke('notify', n),
  download: (url) => ipcRenderer.invoke('download', url),
  voiceState: (st) => ipcRenderer.send('voice-state', st),
  updateStatus:()=>ipcRenderer.invoke('update:status'),
  updateChannel:channel=>ipcRenderer.invoke('update:channel',channel),
  updateReady:()=>ipcRenderer.invoke('update:ready'),
  restartUpdate:()=>ipcRenderer.invoke('update:restart'),
  checkUpdate: (force=false) => ipcRenderer.invoke('update:check',force),
  installUpdate: (info) => ipcRenderer.invoke('update:install', info),
  onUpdateProgress: (fn) => ipcRenderer.on('update:progress', (e, p) => fn(p)),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  version: () => ipcRenderer.invoke('app:version'),
  tun: {
    guestStart: (code) => ipcRenderer.invoke('tun:guest-start', code),
    guestOffer: (sdp, ms) => ipcRenderer.invoke('tun:guest-offer', sdp, ms),
    hostAnswer: (a) => ipcRenderer.invoke('tun:host-answer', a),
    stop: () => ipcRenderer.invoke('tun:stop'),
    ready: (v) => ipcRenderer.send('tun:ready', v),
    open: (k) => ipcRenderer.send('tun:open', k),
    data: (k, b) => ipcRenderer.send('tun:data', k, b),
    close: (k) => ipcRenderer.send('tun:close', k),
    closePeer: (p) => ipcRenderer.send('tun:close-peer', p),
    pause: (k) => ipcRenderer.send('tun:pause', k),
    resume: (k) => ipcRenderer.send('tun:resume', k),
    onEvent: (fn) => ipcRenderer.on('tun:event', (e, ev) => fn(ev)),
  },
  onShortcut: (fn) => ipcRenderer.on('shortcut', (e, action) => fn(action)),
});
